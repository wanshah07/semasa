"""Write the two files made from rules/telegram_menu.json (the Telegram button menu's one catalogue):

  supabase/functions/semasa-telegram/menu_data.js   the webhook's copy of the catalogue. An Edge Function is deployed from its
                                                    own folder, so it cannot read rules/; the copy is this file, word for word.
  rules/telegram_menu_cases.json                    what every menu looks like in both languages, drawn by the worker's
                                                    renderer. The webhook's renderer must draw the same (web/telegramMenu.test.mjs).

Run after any change to rules/telegram_menu.json:   python ops/telegram_menu_copy.py
Both test suites fail while either file is behind (backend/tests/test_telegram_menu.py, web/telegramMenu.test.mjs).
`--check` writes nothing and exits 1 when a file is behind.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from semasa import telegram_menu as menu  # noqa: E402

COPY = ROOT / "supabase" / "functions" / "semasa-telegram" / "menu_data.js"
HEAD = ("// GENERATED by `python ops/telegram_menu_copy.py` from rules/telegram_menu.json. Do not edit: change the JSON and run it\n"
        "// again. web/telegramMenu.test.mjs fails when this copy and the JSON differ.\n")


def copy_text() -> str:
    return HEAD + "export default " + json.dumps(menu.RULES, ensure_ascii=False, indent=2) + ";\n"


def cases_text() -> str:
    return json.dumps(menu.cases(), ensure_ascii=False, indent=1) + "\n"


def main(argv: list[str]) -> int:
    want = {COPY: copy_text(), menu.CASES_PATH: cases_text()}
    behind = [p for p, text in want.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if "--check" in argv:
        for p in behind:
            print(f"behind: {p.relative_to(ROOT)}")
        return 1 if behind else 0
    for p in behind:
        p.write_text(want[p], encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    if not behind:
        print("both files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
