import assert from 'node:assert/strict';
import { effectGroups, effectPolicy, validEffects, assetRefusal } from './src/lib/motionEffects.js';
import { motionRow, motionFromIdea, withDefaults, motionDefaults, motionVariantMatches } from './src/lib/motion.js';
assert.deepEqual(effectGroups().map(g=>g.title), ['Featured Effects','Hooks','Captions','Layouts','Proof','Visual Beats','Animated B-Roll','Signature Effects','Motion Pace','Sound','Colour & Finish']);
assert.equal(new Set(effectGroups().flatMap(g=>g.effects.map(e=>e.id))).size,99);
assert.equal(effectGroups().flatMap(g=>g.effects).length,106);
assert.equal(effectGroups('H06')[1]?.effects.length || effectGroups('H06')[0]?.effects.length,2);
assert.equal(Object.keys(effectPolicy).length,99);
for (const id of ['H01','H03','V01','V03']) {
  assert.equal(effectPolicy[id].adapter,'native-text');
  assert.equal(effectPolicy[id].scope,'authored-heading-only');
  assert.equal(effectPolicy[id].readiness,'ready');
  const queued=motionRow({brief:'Native heading QA',effectMode:'manual',effects:[id]},'owner').row;
  assert.deepEqual(queued.options.effects,[id]);
  assert.equal(queued.options.effect_mode,'manual');
}
assert.equal(Object.values(effectPolicy).filter(e=>e.readiness==='fallback').length,90);
assert.deepEqual(validEffects(['X01','H07','X01']),['X01']);
assert.equal(assetRefusal({name:'../../bad.png',type:'image/png',size:2}) !== '',true);
assert.equal(assetRefusal({name:'good.png',type:'image/png',size:2}),'');
assert.ok(assetRefusal({name:'x.svg',type:'image/svg+xml',size:2}));
assert.ok(assetRefusal({name:'x.png',type:'image/png',size:21*1024*1024}));
const row=motionRow({brief:'original idea',design:'continuous-line',effects:['P01'],assetMode:'mixed',assets:[{path:'owner/x.png'}]},'owner').row;
assert.equal(row.options.design,'continuous-line');
assert.deepEqual(row.options.effects,['P01']);
assert.equal(row.options.asset_mode,'mixed');
assert.equal(row.options.assets[0].path,'owner/x.png');
assert.equal(motionFromIdea({id:'idea',source_title:'Context'}).options.asset_mode,'auto');
assert.deepEqual(motionDefaults({}).effects,['B04']);
assert.deepEqual(withDefaults({}, {effects:['P01'],assetMode:'mixed'}).defaults.effects,['P01']);
assert.equal(motionVariantMatches({...row,status:'done'}, {...row,options:{...row.options,effects:['B08']}}),false);
const { recommendedEffects, toggleEffect, resolveEffects } = await import('./src/lib/motionEffects.js');
assert.deepEqual(recommendedEffects({brief:'Explain a safety process', mode:'explainer'}), ['B04','M03']);
assert.deepEqual(recommendedEffects({brief:'A calm abstract introduction', mode:'teaser'}), ['B08']);
assert.deepEqual(recommendedEffects({assets:[{mime:'image/png',role:'screenshot',source:'Original source'}]}), ['P01','M03']);
assert.deepEqual(toggleEffect(['B04'],'M03'), ['B04','M03']);
assert.deepEqual(toggleEffect(['B04','M03'],'B04'), ['M03']);
assert.deepEqual(resolveEffects({effectMode:'manual',effects:[]}), []);
assert.equal(motionRow({brief:'Explain safety'}).row.options.effect_mode,'auto');
assert.equal(withDefaults({}, {effectMode:'manual',effects:['P01']}).defaults.effectMode,'manual');
const source = await import('node:fs/promises');
const ui = await source.readFile(new URL('./src/components/MotionLab.jsx',import.meta.url),'utf8');
assert.ok(ui.includes('<MotionEffectLibrary'));
assert.ok(ui.includes('design, effects, effectMode, assetMode, assets'));
console.log('motion assets: catalog groups, validation, recommendations, selection and entrypoint contracts passed');
