import assert from 'node:assert/strict';
import { motionRow, motionDefaults, withDefaults, motionFromIdea, motionFromPost, SECONDS } from './src/lib/motion.js';
import { catalog, recipeOf, recipeOptions } from './src/lib/motionStyles.js';
assert.equal(SECONDS.default, 30);
assert.equal(motionRow({brief:'Explain', seconds:10}).row.seconds, 30);
const teaser = motionRow({brief:'Tease', seconds:10, mode:'teaser'}).row;
assert.equal(teaser.seconds, 10);
assert.equal(teaser.options.mode, 'teaser');
const old = motionDefaults({motion:{defaults:{seconds:10}}});
assert.equal(old.seconds, 30);
assert.equal(motionFromIdea({id:'i',source_title:'x'}, null, {seconds:10}).seconds, 30);
assert.equal(motionFromPost({lang:'en',text:{en:{linkedin:'x'}}}, null, {seconds:10}).seconds, 30);
const row = motionRow({brief:'One micro-topic'}).row;
assert.equal(row.mascot, '');
assert.equal(row.options.style, 'bright-education');
assert.equal(row.seconds, 30);
assert.equal(row.language, 'en');
assert.equal(row.voice, 'kitten');
assert.equal(catalog.length, 8);
assert.equal(recipeOf('wrong').id, 'bright-education');
assert.equal(recipeOf('saas-product-demo').id, 'bright-education');
assert.equal(recipeOptions().filter(r => r.available).length, 3); // Auto + bright + financial
assert.equal(motionRow({brief:'x', style:'financial-education-reel'}).row.options.style, 'financial-education-reel');
const saved = withDefaults({prompt:'keep'}, {style:'financial-education-reel', seconds:30, mascot:false});
assert.equal(saved.prompt, 'keep');
assert.equal(motionDefaults({motion:saved}).style, 'financial-education-reel');
assert.equal(motionFromIdea({id:'i',source_title:'x'},null,saved.defaults).options.style, 'financial-education-reel');
assert.equal(motionFromPost({lang:'en',text:{en:{linkedin:'x'}}},null,saved.defaults).options.style,'financial-education-reel');
assert.equal(motionRow({brief:'x',seconds:999}).row.seconds, 60);
assert.equal(motionRow({brief:'x',seconds:''}).row.seconds, 30);
console.log('motionStyles.test.mjs: ok');
